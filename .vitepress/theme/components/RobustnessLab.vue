/** Кількість компонент зв'язності — пошук у ширину по графу сусідства. */
function components(pts: number[][], r: number) {
  const n = pts.length
  if (n === 0) return 0
  const seen = new Array(n).fill(false)
  let comp = 0
  for (let s = 0; s < n; s++) {
    if (seen[s]) continue
    comp++
    const stack = [s]
    seen[s] = true
    while (stack.length) {
      const v = stack.pop()!
      for (let u = 0; u < n; u++) {
        if (seen[u]) continue
        const dx = pts[v][0] - pts[u][0], dy = pts[v][1] - pts[u][1]
        if (dx * dx + dy * dy <= r * r) { seen[u] = true; stack.push(u) }
      }
    }
  }
  return comp
}

const stats = computed(() => {
  let connected = 0
  const comps: number[] = []
  for (let run = 0; run < RUNS; run++) {
    const alive = PERM[run].slice(lost.value).map((i) => POS[i])
    const c = alive.length ? components(alive, radius.value) : 0
    comps.push(c)
    if (c === 1 && alive.length > 1) connected++
  }
  return {
    connectedPct: (connected / RUNS) * 100,
    connectedRuns: connected,
    meanComp: comps.reduce((a, b) => a + b, 0) / RUNS,
    worst: Math.max(...comps),
    alive: N - lost.value
  }
})
